const WD = ["dg", "dl", "dm", "dx", "dj", "dv", "ds"];
/** "2026-12-02" → "dx" */
export const weekdayCode = (iso) => { const [y, m, d] = iso.split("-").map(Number); return WD[new Date(y, m - 1, d).getDay()]; };
export const isoOf = (date) => `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
export const todayIso = () => isoOf(new Date());

const ALL_LX = [...TRIMESTRES.T1.LX, ...TRIMESTRES.T2.LX, ...TRIMESTRES.T3.LX];
const ALL_MJ = [...TRIMESTRES.T1.MJ, ...TRIMESTRES.T2.MJ, ...TRIMESTRES.T3.MJ];
const SETS = { LX: new Set(ALL_LX), MJ: new Set(ALL_MJ), dv: new Set(ANUAL.dv), ds: new Set(ANUAL.ds) };

/** Tipus de calendari d'un grup segons els seus dies de la setmana */
export function calKind(g) {
  const d = (g && g.diesSetmana) || [];
  if (d.includes("dl") || d.includes("dx")) return "LX";
  if (d.includes("dm") || d.includes("dj")) return "MJ";
  if (d.includes("dv")) return "dv";
  if (d.includes("ds")) return "ds";
  return null;
}
/** Té classe aquest grup en aquesta data? */
export const hasSession = (g, iso) => { const k = calKind(g); return !!k && SETS[k].has(iso); };
/** Totes les dates de classe d'un grup */
export const sessionDates = (g) => { const k = calKind(g); return k ? [...SETS[k]].sort() : []; };
/** Trimestre d'una data (T1, T2, T3) o null */
export function trimestreOf(iso) {
  for (const [t, v] of Object.entries(TRIMESTRES)) { const all = [...v.LX, ...v.MJ].sort(); if (iso >= all[0] && iso <= all[all.length - 1]) return t; }
  return null;
}
/** Un alumne que només va uns dies, ve en aquesta data? (el dia de la cloenda venen tots) */
export const comesOn = (dies, iso) => !dies || !dies.length || iso === FESTA_CLOENDA || dies.includes(weekdayCode(iso));
